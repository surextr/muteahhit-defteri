export type SimgeAdi = keyof typeof SIMGELER;

export function Simge({ ad, boyut = '1.15em', className }: { ad: SimgeAdi; boyut?: number | string; className?: string }) {
  const S = SIMGELER[ad];
  return <S size={boyut} strokeWidth={2} aria-hidden="true" focusable="false" className={className ? `simge ${className}` : 'simge'} />;
}
